-- Fase 8 de la auditoría · S7: mínimo privilegio real en la API.
-- Problema: Supabase da por defecto TODOS los privilegios sobre cada tabla, vista, secuencia y función nueva a
-- `anon` y `authenticated`. Las migraciones conceden solo lo necesario, pero esos privilegios por defecto quedaban
-- debajo, así que en Supabase muchas tablas dependían solo de la RLS (p. ej. leer la columna token_hash de
-- email_verifications, actualizar payment_requirements o leer cookie_consent_logs como anónimo). Las pruebas
-- locales no lo veían porque la base local no replicaba esos privilegios (ahora sí: supabase_stub.sql).
-- Arreglo:
--   1. Se retira todo a anon/authenticated en el esquema public y se vuelve a conceder exactamente lo que las
--      migraciones conceden (instantánea generada de una base construida sin privilegios por defecto; las 450+
--      pruebas de RLS validan ese estado).
--   2. Se quitan los privilegios por defecto para objetos futuros: cada migración nueva concede lo suyo.
-- service_role y postgres no cambian. La RLS sigue activa en todas las tablas.
-- ROLLBACK:
--   grant all on all tables in schema public to anon, authenticated;
--   grant all on all sequences in schema public to anon, authenticated;
--   grant execute on all functions in schema public to anon, authenticated;
--   alter default privileges for role postgres in schema public grant all on tables to anon, authenticated;
--   alter default privileges for role postgres in schema public grant all on sequences to anon, authenticated;
--   alter default privileges for role postgres in schema public grant all on functions to anon, authenticated;
-- =============================================================================================================

